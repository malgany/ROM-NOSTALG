// Reproduce the guest's SNES control from the exact EmulatorJS release used by
// the host. Input: a directory containing upstream emulator.js and emulator.css.
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const source = process.argv[2];
if (!source) throw new Error("Usage: node tools/extract-emulator-touch.mjs <upstream-directory>");
const hashes = {
  "emulator.js": "24ebac4baf739892046b82c3bdf01d5b6795b801b77d289e43a4c7d59f9666be",
  "emulator.css": "0ba5b1ce183b6ecb95c17e54e89fbae77697ebb94ec23caca5fd19f9b569defe",
};
const files = {};
for (const [name, expected] of Object.entries(hashes)) {
  const bytes = await readFile(resolve(source, name));
  if (createHash("sha256").update(bytes).digest("hex") !== expected) {
    throw new Error(`Unexpected EmulatorJS 4.2.3 source: ${name}`);
  }
  files[name] = bytes.toString("utf8").replaceAll("\r\n", "\n");
}
function between(text, start, end) {
  const first = text.indexOf(start);
  const last = text.indexOf(end, first + start.length);
  if (first < 0 || last < 0) throw new Error(`Missing upstream section: ${start}`);
  return text.slice(first, last);
}
const js = between(files["emulator.js"], "    setVirtualGamepad() {", "    handleResize() {");
const setup = between(js, '        this.virtualGamepad = this.createElement("div");', "        const speedControlButtons =");
const snes = between(js, '        } else if ("snes" === this.getControlScheme()) {', "            info.push(...speedControlButtons);")
  .replace('        } else if ("snes" === this.getControlScheme()) {\n', "")
  .replace("            info =", "        let info =");
const render = between(js, "        for (let i = 0; i < info.length; i++) {\n            if (info[i].text)", "        info.forEach((zone, index) => {")
  // Let the multiplayer adapter cancel queued releases on disconnect/rotation.
  .replaceAll("window.setTimeout(", "this.deferRelease(");
const header = "/* Extracted from EmulatorJS 4.2.3 (GPL-3.0). See README.md and LICENSE.\n * Generated by tools/extract-emulator-touch.mjs; do not hand-edit. */\n";
const css = between(files["emulator.css"], ".ejs_virtualGamepad_parent {", "@keyframes ejs_settings_parent_animation");
const target = fileURLToPath(new URL("../site/vendor/emulatorjs/4.2.3/", import.meta.url));
await mkdir(target, { recursive: true });
await writeFile(resolve(target, "snes-touch.js"), `${header}"use strict";\nwindow.ROMNostalgSnesTouch = function setVirtualGamepad() {\n${setup}${snes}${render}};\n`);
await writeFile(resolve(target, "snes-touch.css"), header + css.trimEnd() + "\n");
